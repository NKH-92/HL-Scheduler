import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';
import { getArgValue, getCloudflareDeployConfig, normalizeSurface } from './config.mjs';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const repoRoot = path.resolve(__dirname, '..', '..');
const workerRoot = path.resolve(repoRoot, 'server', 'public-schedules-worker');

const surface = normalizeSurface(getArgValue('--surface') || process.env.WORKER_SURFACE);
const config = getCloudflareDeployConfig();
const worker = config.workers[surface];
const outputPath =
  getArgValue('--out') ||
  path.resolve(workerRoot, `wrangler.generated.${config.deployEnv}.${surface}.toml`);

const tomlString = (value) => `"${String(value ?? '').replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;

const fileContents = [
  '# Generated by scripts/cloudflare/render-wrangler-config.mjs',
  `name = ${tomlString(worker.name)}`,
  'main = "src/worker.mjs"',
  'compatibility_date = "2025-02-01"',
  '',
  '[[durable_objects.bindings]]',
  'name = "COLLAB_REALTIME"',
  'class_name = "CollabWorkspaceRoom"',
  '',
  '[[migrations]]',
  'tag = "v1"',
  'new_sqlite_classes = ["CollabWorkspaceRoom"]',
  '',
  '[[d1_databases]]',
  'binding = "DB"',
  `database_name = ${tomlString(config.d1.databaseName)}`,
  `database_id = ${tomlString(config.d1.databaseId)}`,
  `preview_database_id = ${tomlString(config.d1.previewDatabaseId)}`,
  '',
  '[vars]',
  ...Object.entries(worker.vars).map(([key, value]) => `${key} = ${tomlString(value)}`),
  '',
].join('\n');

await mkdir(path.dirname(outputPath), { recursive: true });
await writeFile(outputPath, fileContents, 'utf8');

process.stdout.write(`${outputPath}\n`);
